#!/usr/bin/env python3
"""
Render the publication list into index.html at build time.

The list is plain HTML in the page, not built by client-side JS: crawlers that
do not run JS (most AI crawlers among them) and social scrapers then see every
publication. Written between the PUBS:START / PUBS:END markers inside
<ol id="pub-list">: one <li> per paper with its copy-citation button (wired up
by a small click handler in index.html), plus ScholarlyArticle JSON-LD.

Idempotent: re-running replaces the previously injected block.
Run from anywhere; paths resolve relative to this file.

Usage: python3 render_pubs.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
PUBS = ROOT / "data" / "pubs.json"
JOURNALS = ROOT / "data" / "journals.json"

OWNER = "Shijie Xu"
START = "<!--PUBS:START auto-generated by data/render_pubs.py; do not edit-->"
END = "<!--PUBS:END-->"


def lang(field):
    """researchmap multilingual field -> string (prefer en)."""
    if isinstance(field, dict):
        return field.get("en") or field.get("ja") or ""
    return field or ""


def fmt(s):
    """Escape text, then restore the pKa typography (matches the JS fmt())."""
    return html.escape(s or "").replace("pKa", "p<i>K</i><sub>a</sub>")


def authors_html(people):
    out = []
    for a in people or []:
        name = a.get("name", "")
        is_owner = name.rstrip("*").strip() == OWNER
        esc = html.escape(name)
        out.append(f"<u>{esc}</u>" if is_owner else esc)
    return ", ".join(out)


def tc_badge_html(total, by_year):
    """'TC: N' badge; with a hover per-year bar chart when citations_by_year exists.

    """
    years = sorted(int(y) for y in (by_year or {}) if str(y).isdigit())
    if not years:
        return f'<span class="tc">TC: {total}</span>'
    counts = {int(y): int(c) for y, c in by_year.items() if str(y).isdigit()}
    mx = max(counts.values()) or 1
    bars, aria = [], []
    for y in range(years[0], years[-1] + 1):
        n = counts.get(y, 0)
        h = max(round(n / mx * 100), 8) if n else 0
        cnt = f'<span class="tc-cnt">{n}</span>' if n else ""
        bars.append(
            f'<span class="tc-bar" style="height:{h}%" title="{y}: {n}">'
            f'{cnt}<span class="tc-yr">’{str(y)[2:]}</span></span>'
        )
        if n:
            aria.append(f"{y}: {n}")
    aria_txt = html.escape("Citations per year — " + ", ".join(aria))
    return (
        f'<span class="tc" tabindex="0">TC: {total}'
        f'<span class="tc-pop" role="img" aria-label="{aria_txt}">'
        f'<span class="tc-pop-h">Citations per year</span>'
        f'<span class="tc-plot">{"".join(bars)}</span></span></span>'
    )


def render_li(p, journals, idx):
    journal_name = lang(p.get("publication_name"))
    dois = (p.get("identifiers") or {}).get("doi") or []
    doi = dois[0] if dois else None
    doi_link = f"https://doi.org/{doi}" if doi else None

    authors = f"<span>{authors_html((p.get('authors') or {}).get('en'))}, </span>"
    title = f"<span> “{fmt(lang(p.get('paper_title')))}”, </span>"

    # journal (em)
    if journal_name and "biorxiv" in journal_name.lower():
        img = ('<img src="docs/biorxiv.svg" alt="bioRxiv" class="biorxiv-icon" '
               'style="height:1.2em;vertical-align:middle">')
        inner = f'<a href="{html.escape(doi_link)}">{img}</a>' if doi_link else img
    else:
        jmeta = journals.get(journal_name, {})
        jlabel = html.escape(jmeta.get("abbreviation") or journal_name or "")
        inner = f'<a href="{html.escape(doi_link)}">{jlabel}</a>' if doi_link else jlabel
    journal = f"<em>{inner}</em>"

    # meta (volume/issue/pages/in-press/year)
    vol = p.get("volume") or ""
    num = p.get("number") or ""
    vol_issue = (vol + (f"({num})" if num else "")) if vol else ""
    start_pg = p.get("starting_page") or ""
    end_pg = p.get("ending_page") or ""
    page_range = (f"{start_pg}-{end_pg}" if end_pg else start_pg) if start_pg else ""
    pages = f": {page_range}" if page_range else ""
    in_press = " <em>(in press)</em>" if p.get("in_press") else ""
    year = str(p.get("publication_date") or "")[:4]
    lead = f"{html.escape(vol_issue)}{html.escape(pages)}{in_press}".strip()
    sep = f"{lead}, " if lead else ""
    meta = f"<span> {sep}<strong>{html.escape(year)}</strong></span>"

    parts = [authors, title, journal, meta]

    # media (press release, video, ...) — details live in the "In the News"
    # section; here we only show a small tag that jumps to this paper's entry.
    others = p.get("others")
    if isinstance(others, dict) and others:
        parts.append(
            f'<span style="margin-left:0.5rem">'
            f'<a href="#news-{idx}" class="news-tag">'
            f'<i class="fa-solid fa-newspaper" style="margin-right:0.3em"></i>In the news</a>'
            f'</span>'
        )

    # citation count (with hover per-year chart)
    tc = p.get("is_referenced_by_count")
    by_year = p.get("citations_by_year") or {}
    if isinstance(tc, int) and tc > 0:
        parts.append(f'<span class="pub-badges" style="margin-left:0.5rem">({tc_badge_html(tc, by_year)})</span>')

    # copy-citation button (plain-text reference -> clipboard via the small
    # handler in index.html), kept on the same line as whatever precedes it so
    # it never wraps onto a line by itself
    btn = (f'<button class="copy-btn" type="button" title="Copy citation" '
           f'aria-label="Copy citation" data-cite="{html.escape(citation(p), quote=True)}">'
           f'<i class="fa-regular fa-copy"></i></button>')
    parts[-1] = f'<span style="white-space:nowrap">{parts[-1]}{btn}</span>'

    return "      <li>" + "".join(parts) + "</li>"


def citation(p):
    """Plain-text reference for the copy button."""
    journal_name = lang(p.get("publication_name"))
    dois = (p.get("identifiers") or {}).get("doi") or []
    vol, num = p.get("volume") or "", p.get("number") or ""
    start_pg, end_pg = p.get("starting_page") or "", p.get("ending_page") or ""
    year = str(p.get("publication_date") or "")[:4]
    s = ", ".join(a.get("name", "") for a in (p.get("authors") or {}).get("en") or [])
    s += f'. "{lang(p.get("paper_title"))}." {journal_name}'
    if vol:
        s += f" {vol}" + (f"({num})" if num else "")
    if start_pg:
        s += f": {start_pg}-{end_pg}" if end_pg else f": {start_pg}"
    if p.get("in_press"):
        s += " (in press)"
    if year:
        s += f", {year}"
    s += "."
    if dois:
        s += f" https://doi.org/{dois[0]}"
    return s


def jsonld(pubs):
    """One ScholarlyArticle per publication, so each paper is indexable."""
    articles = []
    for p in pubs:
        dois = (p.get("identifiers") or {}).get("doi") or []
        node = {
            "@context": "https://schema.org",
            "@type": "ScholarlyArticle",
            "headline": lang(p.get("paper_title")),
            "name": lang(p.get("paper_title")),
            "author": [{"@type": "Person", "name": a.get("name", "").rstrip("*")}
                       for a in (p.get("authors") or {}).get("en") or []],
            "datePublished": str(p.get("publication_date") or "")[:4],
            "isPartOf": {"@type": "Periodical", "name": lang(p.get("publication_name"))},
        }
        if dois:
            node["identifier"] = {"@type": "PropertyValue", "propertyID": "DOI", "value": dois[0]}
            node["sameAs"] = node["url"] = f"https://doi.org/{dois[0]}"
        if p.get("volume"):
            node["isPartOf"]["volumeNumber"] = p["volume"]
        articles.append(node)
    data = json.dumps(articles, ensure_ascii=False).replace("</", "<\\/")
    return f'      <script type="application/ld+json">{data}</script>'


def main():
    pubs = json.loads(PUBS.read_text(encoding="utf-8"))
    journals = {}
    if JOURNALS.exists():
        journals = json.loads(JOURNALS.read_text(encoding="utf-8"))

    items = "\n".join(render_li(p, journals, i) for i, p in enumerate(pubs))
    # <script> is allowed inside <ol>, so the JSON-LD travels with the list
    block = f"{START}\n{items}\n{jsonld(pubs)}\n      {END}"

    text = INDEX.read_text(encoding="utf-8")
    ol_re = re.compile(r'(<ol id="pub-list"[^>]*>)(.*?)(</ol>)', re.DOTALL)
    if not ol_re.search(text):
        raise SystemExit('error: <ol id="pub-list"> not found in index.html')
    text = ol_re.sub(lambda m: f"{m.group(1)}\n      {block}\n    {m.group(3)}", text)

    INDEX.write_text(text, encoding="utf-8")
    print(f"Injected {len(pubs)} publication(s) into index.html.")


if __name__ == "__main__":
    main()
